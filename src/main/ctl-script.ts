// src/main/ctl-script.ts
// Generates the vibeyard-ctl client. Python, like the statusline/hook helpers
// in ~/.vibeyard/run, because the app already requires it and a bare .app
// install has no `vibeyard` on PATH. Reinstalled on every launch; ctl.py is
// shared by every running Vibeyard, so it holds no per-instance values: the
// commands folder comes from VIBEYARD_CTL_DIR, which each instance gives its tabs.
import * as fs from 'fs';
import * as path from 'path';
import { isWin, pythonBin } from './platform';
import { CTL_BIN_DIR, CTL_COMMAND_PATH } from './ctl-paths';
import { CTL_MAX_PROMPT_CHARS } from '../shared/ctl-protocol';
import { TASK_PRIORITIES } from '../shared/types';

export function buildCtlPython(): string {
  return String.raw`#!/usr/bin/env python3
# vibeyard-ctl: control Vibeyard tabs from inside a Vibeyard tab. Generated by Vibeyard; do not edit.
import argparse, json, os, sys, time, uuid

# This Vibeyard instance's own request folder (~/.vibeyard/commands/<pid>-<hex>).
COMMANDS_DIR = os.environ.get("VIBEYARD_CTL_DIR", "")
START_ERROR_FILE = COMMANDS_DIR + ".error"
MAX_PROMPT = ${CTL_MAX_PROMPT_CHARS}
PRIORITIES = ${JSON.stringify(TASK_PRIORITIES)}
BOARD_NOTE = (
    "Task ids may be shortened to a unique prefix of 4+ characters. Without --project "
    "a command uses the calling tab's project; pass --project to reach a task on another "
    "project's board. In a remote (SSH) session only the board commands work, always on "
    "the session's own project."
)
DEFAULT_TIMEOUT = 10.0
WINDOWS_NOTE = (
    "On Windows, vibeyard-ctl.cmd runs through cmd.exe, which expands %VAR%, "
    "drops ^ and !, and cuts arguments at newlines. Pass any prompt containing "
    "newlines, %, ^ or ! with --prompt-file, and keep --name and other values simple."
)

def out(obj, code):
    sys.stdout.write(json.dumps(obj) + "\n")
    sys.stdout.flush()
    sys.exit(code)

def fail(code, message, exit_code=1):
    out({"ok": False, "error": {"code": code, "message": message}}, exit_code)

class Parser(argparse.ArgumentParser):
    def error(self, message):
        fail("invalid_request", message)

def build_parser():
    p = Parser(prog="vibeyard-ctl", description="Control Vibeyard tabs from inside a Vibeyard tab.", epilog=WINDOWS_NOTE)
    sub = p.add_subparsers(dest="action")
    n = sub.add_parser("new-session", epilog=WINDOWS_NOTE)
    n.add_argument("--name", required=True)
    n.add_argument("--project")
    g = n.add_mutually_exclusive_group()
    g.add_argument("--prompt")
    g.add_argument("--prompt-file", help="read the prompt from this UTF-8 file (use it on Windows for special characters)")
    n.add_argument("--provider")
    n.add_argument("--profile")
    n.add_argument("--focus", action="store_true")
    r = sub.add_parser("rename")
    r.add_argument("session_id")
    r.add_argument("name")
    c = sub.add_parser("close")
    c.add_argument("session_id")
    l = sub.add_parser("list")
    l.add_argument("--project")
    l.add_argument("--mine", action="store_true")
    b = sub.add_parser("board", help="read and edit the project's Kanban board (tasks)", epilog=BOARD_NOTE)
    bs = b.add_subparsers(dest="board_action")
    bl = bs.add_parser("list", help="columns and tasks")
    bl.add_argument("--project")
    bl.add_argument("--column", help="only this column (id or title)")
    bl.add_argument("--tag")
    bl.add_argument("--priority", choices=PRIORITIES)
    bsh = bs.add_parser("show")
    bsh.add_argument("task_id")
    bsh.add_argument("--project")
    ba = bs.add_parser("add")
    ba.add_argument("--title", required=True)
    ba.add_argument("--project")
    text_args(ba)
    ba.add_argument("--column", help="id or title; default: the inbox column")
    ba.add_argument("--tag", action="append", dest="tags")
    ba.add_argument("--priority", choices=PRIORITIES)
    bu = bs.add_parser("update")
    bu.add_argument("task_id")
    bu.add_argument("--project")
    bu.add_argument("--title")
    text_args(bu)
    bu.add_argument("--priority", choices=PRIORITIES + ["none"])
    bu.add_argument("--add-tag", action="append", dest="add_tags")
    bu.add_argument("--remove-tag", action="append", dest="remove_tags")
    bm = bs.add_parser("move")
    bm.add_argument("task_id")
    bm.add_argument("--column", required=True, help="id or title")
    bm.add_argument("--position", type=int, help="0 = top; default: bottom")
    bm.add_argument("--project")
    bd = bs.add_parser("delete")
    bd.add_argument("task_id")
    bd.add_argument("--project")
    return p

def text_args(parser):
    for name in ("prompt", "notes"):
        g = parser.add_mutually_exclusive_group()
        g.add_argument("--" + name)
        g.add_argument("--%s-file" % name, help="read the %s from this UTF-8 file" % name)

def read_text(a, name):
    value = getattr(a, name)
    path = getattr(a, name + "_file")
    if path:
        try:
            with open(path, "r", encoding="utf-8", newline="") as f:
                value = f.read(MAX_PROMPT + 1)
        except OSError as e:
            fail("invalid_request", "cannot read --%s-file: %s" % (name, e))
    if value is not None and len(value) > MAX_PROMPT:
        fail("invalid_request", "%s is longer than %d characters" % (name, MAX_PROMPT))
    return value

def board_command(a):
    ba = a.board_action
    if not ba:
        fail("invalid_request", "missing board command: list, show, add, update, move or delete")
    cmd = {"action": "board-" + ba}
    if getattr(a, "task_id", None) is not None:
        cmd["taskId"] = a.task_id
    keys = {"project": "project", "column": "column", "tag": "tag", "priority": "priority",
            "title": "title", "tags": "tags", "position": "position",
            "add_tags": "addTags", "remove_tags": "removeTags"}
    for attr, key in keys.items():
        v = getattr(a, attr, None)
        if v is not None:
            cmd[key] = v
    if ba in ("add", "update"):
        for name in ("prompt", "notes"):
            v = read_text(a, name)
            if v is not None:
                cmd[name] = v
    return cmd

def to_command(a):
    if a.action == "new-session":
        cmd = {"action": "new-session", "name": a.name}
        prompt = read_text(a, "prompt")
        if prompt is not None:
            cmd["prompt"] = prompt
        for key in ("project", "provider", "profile"):
            v = getattr(a, key)
            if v is not None:
                cmd[key] = v
        if a.focus:
            cmd["focus"] = True
        return cmd
    if a.action == "rename":
        return {"action": "rename", "sessionId": a.session_id, "name": a.name}
    if a.action == "close":
        return {"action": "close", "sessionId": a.session_id}
    if a.action == "board":
        return board_command(a)
    if a.action == "list":
        cmd = {"action": "list"}
        if a.project is not None:
            cmd["project"] = a.project
        if a.mine:
            cmd["mine"] = True
        return cmd
    fail("invalid_request", "missing command: new-session, rename, close, list or board")

def timeout_seconds():
    try:
        return float(os.environ.get("VIBEYARD_CTL_TIMEOUT", DEFAULT_TIMEOUT))
    except ValueError:
        return DEFAULT_TIMEOUT

def start_error():
    try:
        with open(START_ERROR_FILE, "r", encoding="utf-8", errors="replace") as f:
            return f.read(4096).strip()
    except OSError:
        return None

def main():
    a = build_parser().parse_args()
    command = to_command(a)
    token = os.environ.get("VIBEYARD_CTL_TOKEN", "")
    if not token or not COMMANDS_DIR:
        fail("unauthorized", "vibeyard-ctl only works inside a Vibeyard tab (VIBEYARD_CTL_TOKEN/VIBEYARD_CTL_DIR not set)")
    if not os.path.exists(os.path.join(COMMANDS_DIR, ".enabled")):
        reason = start_error()
        if reason:
            fail("disabled", "external control could not start: %s" % reason)
        fail("disabled", "external control is disabled in Vibeyard preferences")
    req_id = uuid.uuid4().hex
    req = os.path.join(COMMANDS_DIR, req_id + ".json")
    res = os.path.join(COMMANDS_DIR, req_id + ".result.json")
    tmp = req + ".tmp"
    with open(tmp, "w", encoding="utf-8") as f:
        json.dump({"v": 1, "token": token, "command": command}, f, ensure_ascii=False)
    os.replace(tmp, req)
    deadline = time.time() + timeout_seconds()
    while time.time() < deadline:
        if os.path.exists(res):
            try:
                with open(res, "r", encoding="utf-8") as f:
                    result = json.load(f)
            except (OSError, ValueError):
                time.sleep(0.05)
                continue
            try:
                os.remove(res)
            except OSError:
                pass
            out(result, 0 if result.get("ok") else 1)
        time.sleep(0.05)
    try:
        os.remove(req)
    except OSError:
        pass
    fail("timeout", "Vibeyard did not answer (is it running?)", 2)

if __name__ == "__main__":
    main()
`;
}

export function installCtlScript(): void {
  fs.mkdirSync(CTL_BIN_DIR, { recursive: true, mode: 0o700 });
  const pyPath = path.join(CTL_BIN_DIR, 'ctl.py');
  fs.writeFileSync(pyPath, buildCtlPython(), { mode: 0o755 });
  const wrapper = isWin
    ? `@echo off\r\n${pythonBin} "${pyPath}" %*\r\n`
    : `#!/bin/sh\nexec ${pythonBin} "${pyPath}" "$@"\n`;
  fs.writeFileSync(CTL_COMMAND_PATH, wrapper, { mode: 0o755 });
}
